/**
 * Generates src/styles/office-fonts.css: @font-face rules that make
 * the fonts Office documents ask for (Calibri, Cambria, Arial, Times
 * New Roman, Courier New) resolve to bundled, metric-compatible open
 * fonts when the real ones are not installed (every phone).
 *
 * Metric-compatible means every glyph has the same advance width as
 * the original, so lines break and pages fill exactly as authored.
 *
 *   Calibri         -> Carlito   (SIL OFL)
 *   Cambria         -> Caladea   (Apache 2.0 / OFL)
 *   Arial/Helvetica -> Arimo     (Apache 2.0)
 *   Times New Roman -> Tinos     (Apache 2.0)
 *   Courier New     -> Cousine   (Apache 2.0)
 *
 * An installed copy of the real font always wins (local()). The files
 * come from the @fontsource packages; nothing is fetched at runtime.
 *
 * Run: node scripts/make-office-fonts.mjs
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const FAMILIES = [
	{ pkg: "carlito", names: ["Calibri", "Calibri Light"] },
	{ pkg: "caladea", names: ["Cambria"] },
	{ pkg: "arimo", names: ["Arial", "Helvetica"] },
	{ pkg: "tinos", names: ["Times New Roman"] },
	{ pkg: "cousine", names: ["Courier New"] },
];
const VARIANTS = ["400", "400-italic", "700", "700-italic"];

let css = `/* Generated by scripts/make-office-fonts.mjs. Do not edit by hand.
 * Metric-compatible stand-ins for the fonts Office documents name. */\n`;
let faces = 0;

for (const { pkg, names } of FAMILIES) {
	const dir = join(root, "node_modules", "@fontsource", pkg);
	for (const variant of VARIANTS) {
		const file = join(dir, `${variant}.css`);
		if (!existsSync(file)) {
			console.error(`missing ${file}: run npm install`);
			process.exit(1);
		}
		const blocks =
			readFileSync(file, "utf8").match(/@font-face\s*{[^}]*}/g) ?? [];
		for (const block of blocks) {
			const style = /font-style:\s*([^;]+);/.exec(block)?.[1].trim();
			const weight = /font-weight:\s*([^;]+);/.exec(block)?.[1].trim();
			const woff2 = /url\(\.\/(files\/[^)]+\.woff2)\)/.exec(block)?.[1];
			const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1].trim();
			if (!style || !weight || !woff2) continue;
			for (const name of names) {
				const local = `local("${name}"), `;
				css += `@font-face {
	font-family: "${name}";
	font-style: ${style};
	font-weight: ${weight};
	font-display: swap;
	src: ${local}url("@fontsource/${pkg}/${woff2}") format("woff2");${range ? `\n\tunicode-range: ${range};` : ""}
}\n`;
				faces++;
			}
		}
	}
}

writeFileSync(join(root, "src", "styles", "office-fonts.css"), css);
console.log(`wrote src/styles/office-fonts.css (${faces} faces)`);
